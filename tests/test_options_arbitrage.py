"""No-arbitrage checks against a synthetic chain built from Black-76.

The clean chain is generated by the pricer, so it satisfies every inequality
by construction. That makes false positives visible: any finding on it is the
check's fault, not the data's. Violations are then planted one at a time.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

import pytest

from eulerlab.master.derivatives import ContractType, Right
from eulerlab.options.arbitrage import (
    check_butterfly_convexity,
    check_calendar_monotonicity,
    check_intrinsic_bounds,
    check_put_call_parity,
    check_strike_monotonicity,
    implied_forward_and_discount,
    run_chain_checks,
)
from eulerlab.options.chain import Chain, Quote
from eulerlab.options.iv import black76_price
from eulerlab.quality.findings import Severity

DAY = date(2026, 8, 19)
EXPIRY = date(2026, 9, 24)
FORWARD, DISCOUNT, VOL, YEARS = 20000.0, 0.995, 0.15, 36 / 365


def _quote(strike: float, right: Right, price: float, volume: float = 100.0) -> Quote:
    return Quote(
        underlying="NIFTY",
        expiry=EXPIRY,
        contract_type=ContractType.OPTION,
        price=price,
        strike=Decimal(str(strike)),
        right=right,
        volume=volume,
    )


def clean_chain(strikes: list[float] | None = None) -> Chain:
    """A chain priced by Black-76: arbitrage-free by construction."""
    strikes = strikes or [19000.0, 19500.0, 20000.0, 20500.0, 21000.0]
    chain = Chain(underlying="NIFTY", expiry=EXPIRY, day=DAY)
    for k in strikes:
        for right, store in ((Right.CALL, chain.calls), (Right.PUT, chain.puts)):
            price = black76_price(
                forward=FORWARD, strike=k, years=YEARS, vol=VOL, discount=DISCOUNT, right=right
            )
            store[Decimal(str(k))] = _quote(k, right, round(price, 2))
    return chain


# --- no false positives on a clean chain ---


def test_a_black76_chain_produces_no_findings() -> None:
    """The baseline. Any finding here is the check's fault."""
    assert run_chain_checks(clean_chain()) == []


def test_the_forward_and_discount_are_recovered_from_the_chain() -> None:
    """No risk-free rate is assumed; both come out of the parity regression."""
    fitted = implied_forward_and_discount(clean_chain())
    assert fitted is not None
    forward, discount = fitted
    assert forward == pytest.approx(FORWARD, abs=1.0)
    assert discount == pytest.approx(DISCOUNT, abs=0.001)


# --- planted violations ---


def test_a_broken_parity_is_found() -> None:
    """The planted error must exceed 2% of the forward, which is the measured
    p99.6 of the real residual distribution - 400 points on a 20,000 index."""
    chain = clean_chain()
    k = Decimal("20000.0")
    chain.calls[k] = _quote(20000.0, Right.CALL, chain.calls[k].price + 900)
    findings = check_put_call_parity(chain)
    assert findings
    assert findings[0].check == "put-call-parity"


def test_a_residual_inside_the_measured_tolerance_is_not_flagged() -> None:
    """300 points on a 20,000 forward is 1.5% - inside the p99 of what real
    settlement prices actually do, so flagging it would be noise."""
    chain = clean_chain()
    k = Decimal("20000.0")
    chain.calls[k] = _quote(20000.0, Right.CALL, chain.calls[k].price + 300)
    assert check_put_call_parity(chain) == []


def test_the_parity_slack_scales_with_the_underlying() -> None:
    """The correction this calibration made. An absolute rupee slack is 0.2%
    on a 24,000 index and 50% on a Rs 100 stock; measured on real data an
    absolute Rs 1.00 flagged 45.95% of all traded pairs."""
    from eulerlab.options.arbitrage import MIN_PARITY_SLACK, PARITY_SLACK_FRACTION

    assert PARITY_SLACK_FRACTION * 20000.0 > MIN_PARITY_SLACK
    # A cheap underlying still gets at least tick-scale slack.
    assert max(PARITY_SLACK_FRACTION * 10.0, MIN_PARITY_SLACK) == MIN_PARITY_SLACK


def test_a_call_more_expensive_at_a_higher_strike_is_found() -> None:
    chain = clean_chain()
    k = Decimal("21000.0")
    chain.calls[k] = _quote(21000.0, Right.CALL, 9999.0)
    assert any(f.check == "call-monotonicity" for f in check_strike_monotonicity(chain))


def test_a_put_cheaper_at_a_higher_strike_is_found() -> None:
    chain = clean_chain()
    k = Decimal("21000.0")
    chain.puts[k] = _quote(21000.0, Right.PUT, 0.05)
    assert any(f.check == "put-monotonicity" for f in check_strike_monotonicity(chain))


def test_a_negative_butterfly_is_found() -> None:
    """A butterfly has a non-negative payoff, so it cannot cost less than zero."""
    chain = clean_chain()
    k = Decimal("20000.0")
    chain.calls[k] = _quote(20000.0, Right.CALL, chain.calls[k].price + 500)
    assert any(f.check == "call-butterfly" for f in check_butterfly_convexity(chain))


def test_a_call_below_intrinsic_is_an_error_not_a_warning() -> None:
    """Unlike a parity drift this is a contradiction, not a rounding artefact."""
    chain = clean_chain()
    k = Decimal("19000.0")
    chain.calls[k] = _quote(19000.0, Right.CALL, 1.0)
    findings = check_intrinsic_bounds(chain)
    assert findings
    assert findings[0].severity is Severity.ERROR


# --- the traded/untraded split, which decides what a violation means ---


def test_untraded_contracts_are_excluded_by_default() -> None:
    """NSE computes a settlement price for strikes that never traded, so a
    violation there is about NSE's model, not the market."""
    chain = clean_chain()
    k = Decimal("21000.0")
    chain.calls[k] = _quote(21000.0, Right.CALL, 9999.0, volume=0.0)
    assert check_strike_monotonicity(chain, traded_only=True) == []


def test_untraded_contracts_are_checked_when_asked_for() -> None:
    chain = clean_chain()
    k = Decimal("21000.0")
    chain.calls[k] = _quote(21000.0, Right.CALL, 9999.0, volume=0.0)
    assert check_strike_monotonicity(chain, traded_only=False)


# --- guards against manufactured findings ---


def test_unequally_spaced_strikes_are_skipped_for_butterflies() -> None:
    """The equal-spacing formula applied to an uneven ladder manufactures
    violations that are artefacts of the strikes, not the prices."""
    chain = clean_chain([19000.0, 19500.0, 21000.0])
    assert check_butterfly_convexity(chain) == []


def test_too_few_strikes_produce_no_fit_rather_than_a_bad_one() -> None:
    chain = clean_chain([20000.0, 20500.0])
    assert implied_forward_and_discount(chain) is None
    assert check_put_call_parity(chain) == []


def test_an_empty_chain_is_handled() -> None:
    chain = Chain(underlying="NIFTY", expiry=EXPIRY, day=DAY)
    assert run_chain_checks(chain) == []


# --- calendar ---


def test_a_far_month_worth_far_less_than_the_near_month_is_flagged() -> None:
    """The signature of a stale mark on a thin far-dated contract."""
    near = clean_chain()
    far = Chain(underlying="NIFTY", expiry=date(2026, 12, 31), day=DAY)
    for k, quote in near.calls.items():
        far.calls[k] = Quote(
            underlying="NIFTY",
            expiry=date(2026, 12, 31),
            contract_type=ContractType.OPTION,
            price=quote.price * 0.1,
            strike=k,
            right=Right.CALL,
            volume=10.0,
        )
    assert check_calendar_monotonicity([near, far])


def test_a_normal_term_structure_is_not_flagged() -> None:
    near = clean_chain()
    far = Chain(underlying="NIFTY", expiry=date(2026, 12, 31), day=DAY)
    for k, quote in near.calls.items():
        far.calls[k] = Quote(
            underlying="NIFTY",
            expiry=date(2026, 12, 31),
            contract_type=ContractType.OPTION,
            price=quote.price * 1.6,
            strike=k,
            right=Right.CALL,
            volume=10.0,
        )
    assert check_calendar_monotonicity([near, far]) == []


# --- the fit must survive the corruption it exists to find ---


def test_the_fit_survives_a_single_wildly_wrong_price() -> None:
    """The bug this module's docstring is about.

    With ordinary least squares, planting one call at Rs 1.00 when its
    intrinsic was Rs 1,000 skewed the fit so far that the discount factor left
    the plausible range, the fit returned None, and the intrinsic check
    reported nothing. The corruption hid itself perfectly by destroying the
    benchmark used to detect it.

    Theil-Sen takes the median of pairwise slopes, so one bad point cannot
    move it. The fit stays close to the truth and the violation is caught.
    """
    chain = clean_chain()
    chain.calls[Decimal("19000.0")] = _quote(19000.0, Right.CALL, 1.0)

    fitted = implied_forward_and_discount(chain)
    assert fitted is not None
    forward, discount = fitted
    assert forward == pytest.approx(FORWARD, abs=5.0)
    assert discount == pytest.approx(DISCOUNT, abs=0.01)

    assert any(f.severity is Severity.ERROR for f in check_intrinsic_bounds(chain))


def test_the_fit_survives_two_wrong_prices_out_of_five() -> None:
    """Theil-Sen tolerates roughly 29% corruption. Two of five is 40%, which
    is past that, so this pins where it actually breaks rather than claiming
    more than it delivers."""
    chain = clean_chain([19000.0, 19500.0, 20000.0, 20500.0, 21000.0])
    chain.calls[Decimal("19000.0")] = _quote(19000.0, Right.CALL, 1.0)
    chain.calls[Decimal("21000.0")] = _quote(21000.0, Right.CALL, 5000.0)

    fitted = implied_forward_and_discount(chain)
    # Either it still fits usably, or it declines to answer. What it must not
    # do is return a confidently wrong forward.
    if fitted is not None:
        forward, _ = fitted
        assert abs(forward - FORWARD) < 2000.0
